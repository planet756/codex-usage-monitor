// Package i18n owns the companion's small native UI vocabulary.
package i18n

import "fmt"

func Text(language, english string) string {
	if language == "zh-CN" {
		if chinese, ok := zh[english]; ok {
			return chinese
		}
	}
	return english
}

func Format(language, english string, args ...any) string {
	return fmt.Sprintf(Text(language, english), args...)
}

